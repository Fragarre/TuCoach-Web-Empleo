-- Cola de avisos de seguimiento (novedades de oportunidades seguidas).
-- Migración aditiva e idempotente: permite reintentar avisos fallidos.

CREATE TABLE IF NOT EXISTS empleo_avisos_seguimiento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL,
    novedad_tipo TEXT NOT NULL CHECK (novedad_tipo IN ('PUBLICACION','CAMBIO')),
    novedad_id BIGINT NOT NULL,
    estado TEXT NOT NULL DEFAULT 'PENDIENTE'
        CHECK (estado IN ('PENDIENTE','ENVIADA','DESCARTADA')),
    error TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    enviado_at TIMESTAMPTZ,
    CONSTRAINT uq_empleo_avisos_seguimiento UNIQUE (user_id, novedad_tipo, novedad_id)
);

CREATE INDEX IF NOT EXISTS idx_empleo_avisos_seguimiento_pendientes
    ON empleo_avisos_seguimiento(estado, created_at);

ALTER TABLE empleo_avisos_seguimiento ENABLE ROW LEVEL SECURITY;
